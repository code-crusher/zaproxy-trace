package org.parosproxy.paros.db.paros;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Test helper that provides in-memory HSQLDB connections with the tables needed by the {@code
 * ParosTable*} tests.
 */
final class HsqldbTestTables {

    private static final AtomicInteger DB_COUNTER = new AtomicInteger();

    private static final String CREATE_HISTORY =
            "CREATE CACHED TABLE HISTORY ("
                    + "HISTORYID INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL PRIMARY KEY,"
                    + "SESSIONID BIGINT NOT NULL,"
                    + "HISTTYPE INTEGER DEFAULT 1,"
                    + "STATUSCODE INTEGER DEFAULT 0,"
                    + "TIMESENTMILLIS BIGINT DEFAULT 0,"
                    + "TIMEELAPSEDMILLIS INTEGER DEFAULT 0,"
                    + "METHOD VARCHAR(1024) DEFAULT '',"
                    + "URI VARCHAR(1048576) DEFAULT '',"
                    + "REQHEADER VARCHAR(4194304) DEFAULT '',"
                    + "REQBODY VARBINARY(16777216) DEFAULT X'',"
                    + "RESHEADER VARCHAR(4194304) DEFAULT '',"
                    + "RESBODY VARBINARY(16777216) DEFAULT X'',"
                    + "TAG VARCHAR(32768) DEFAULT '',"
                    + "NOTE VARCHAR(1048576) DEFAULT '',"
                    + "RESPONSEFROMTARGETHOST BOOLEAN DEFAULT FALSE)";

    private static final String CREATE_ALERT =
            "CREATE CACHED TABLE ALERT ("
                    + "ALERTID INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 0) NOT NULL PRIMARY KEY,"
                    + "SCANID INTEGER NOT NULL,"
                    + "PLUGINID INTEGER DEFAULT 0,"
                    + "ALERT VARCHAR(16777216) DEFAULT '',"
                    + "RISK INTEGER DEFAULT 0,"
                    + "RELIABILITY INTEGER DEFAULT 1,"
                    + "DESCRIPTION VARCHAR(16777216) DEFAULT '',"
                    + "URI VARCHAR(1048576) DEFAULT '',"
                    + "PARAM VARCHAR(32768) DEFAULT '',"
                    + "OTHERINFO VARCHAR(16777216) DEFAULT '',"
                    + "SOLUTION VARCHAR(16777216) DEFAULT '',"
                    + "REFERENCE VARCHAR(16777216) DEFAULT '',"
                    + "HISTORYID INTEGER,"
                    + "SOURCEHISTORYID INTEGER DEFAULT 0,"
                    + "ATTACK VARCHAR(32768) DEFAULT '',"
                    + "EVIDENCE VARCHAR(16777216) DEFAULT '',"
                    + "CWEID INTEGER DEFAULT -1,"
                    + "WASCID INTEGER DEFAULT -1,"
                    + "SOURCEID INTEGER DEFAULT 0,"
                    + "ALERTREF VARCHAR(256) DEFAULT '',"
                    + "INPUT_VECTOR VARCHAR(256) DEFAULT '',"
                    + "NODENAME VARCHAR(1048576) DEFAULT NULL)";

    private static final String CREATE_ALERT_INDEX =
            "CREATE INDEX ALERT_INDEX ON ALERT (SOURCEHISTORYID)";

    private HsqldbTestTables() {}

    /**
     * Creates a new in-memory database and returns a connection to it.
     *
     * @return a connection to a new in-memory database, never {@code null}.
     * @throws SQLException if an error occurred while creating the database.
     */
    static Connection newConnection() throws SQLException {
        return DriverManager.getConnection(
                "jdbc:hsqldb:mem:zaptest" + DB_COUNTER.incrementAndGet(), "sa", "");
    }

    /**
     * Creates a connection with an empty {@code HISTORY} table.
     *
     * @return a connection to a new in-memory database with a {@code HISTORY} table.
     * @throws SQLException if an error occurred while creating the database.
     */
    static Connection newConnectionWithHistoryTable() throws SQLException {
        Connection connection = newConnection();
        try {
            execute(connection, CREATE_HISTORY);
        } catch (SQLException e) {
            connection.close();
            throw e;
        }
        return connection;
    }

    /**
     * Creates a connection with an empty {@code ALERT} table.
     *
     * @return a connection to a new in-memory database with an {@code ALERT} table.
     * @throws SQLException if an error occurred while creating the database.
     */
    static Connection newConnectionWithAlertTable() throws SQLException {
        Connection connection = newConnection();
        try {
            execute(connection, CREATE_ALERT);
            execute(connection, CREATE_ALERT_INDEX);
        } catch (SQLException e) {
            connection.close();
            throw e;
        }
        return connection;
    }

    private static void execute(Connection connection, String sql) throws SQLException {
        try (Statement stmt = connection.createStatement()) {
            stmt.execute(sql);
        }
    }
}
