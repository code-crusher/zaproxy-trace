package org.parosproxy.paros.db.paros;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.parosproxy.paros.db.RecordTag;

/**
 * Unit test for {@link ParosTableTag}.
 *
 * <p>Verifies that the TAG table has an index on HISTORYID, which is required for acceptable
 * performance of the lookups done while passively scanning (issue 9278).
 */
class ParosTableTagUnitTest {

    private static final String INDEX_NAME = "TAG_HISTORYID_INDEX";

    private Connection connection;
    private ParosTableTag table;

    @BeforeEach
    void setUp() throws Exception {
        connection = DriverManager.getConnection("jdbc:hsqldb:mem:ParosTableTagUnitTest", "sa", "");
        table = new ParosTableTag();
    }

    @AfterEach
    void tearDown() throws Exception {
        try (Statement stmt = connection.createStatement()) {
            stmt.execute("DROP TABLE TAG IF EXISTS");
        }
        connection.close();
    }

    private void reconnect() throws Exception {
        // reconnect(Connection) is protected in ParosAbstractTable.
        java.lang.reflect.Method reconnect = null;
        for (Class<?> c = table.getClass(); c != null; c = c.getSuperclass()) {
            try {
                reconnect = c.getDeclaredMethod("reconnect", Connection.class);
                break;
            } catch (NoSuchMethodException e) {
                // Walk up the hierarchy.
            }
        }
        reconnect.setAccessible(true);
        reconnect.invoke(table, connection);
    }

    @Test
    void shouldCreateIndexOnHistoryIdWhenCreatingTable() throws Exception {
        // Given / When
        reconnect();
        // Then
        assertTrue(hasIndex(), "The TAG table should have the index " + INDEX_NAME);
    }

    @Test
    void shouldCreateIndexOnHistoryIdWhenTableAlreadyExists() throws Exception {
        // Given an existing TAG table without the index (e.g. older session)
        try (Statement stmt = connection.createStatement()) {
            stmt.execute(
                    "CREATE CACHED TABLE TAG (tagid bigint generated by default as identity"
                            + " (start with 1), historyid bigint not null, tag varchar(1024) default '')");
        }
        assertFalse(hasIndex());
        // When
        reconnect();
        // Then
        assertTrue(hasIndex(), "The index should be added to pre-existing TAG tables");
    }

    @Test
    void shouldInsertAndReadTags() throws Exception {
        // Given
        reconnect();
        // When
        table.insert(1, "Form");
        table.insert(1, "Script");
        List<RecordTag> tags = table.getTagsForHistoryID(1);
        // Then
        assertEquals(2, tags.size());
        assertEquals("Form", tags.get(0).getTag());
        assertEquals("Script", tags.get(1).getTag());
    }

    @Test
    void shouldDeleteTagsForHistoryId() throws Exception {
        // Given
        reconnect();
        table.insert(1, "Form");
        table.insert(2, "Script");
        // When
        table.deleteTagsForHistoryID(1);
        // Then
        assertTrue(table.getTagsForHistoryID(1).isEmpty());
        assertEquals(1, table.getTagsForHistoryID(2).size());
    }

    @Test
    void shouldDeleteTag() throws Exception {
        // Given
        reconnect();
        table.insert(1, "Form");
        // When
        table.delete(1, "Form");
        // Then
        assertTrue(table.getTagsForHistoryID(1).isEmpty());
    }

    private boolean hasIndex() throws SQLException {
        boolean hasIndex = false;
        try (ResultSet rs =
                connection.getMetaData().getIndexInfo(null, null, "TAG", false, false)) {
            while (rs.next()) {
                if (INDEX_NAME.equals(rs.getString("INDEX_NAME"))) {
                    hasIndex = true;
                    break;
                }
            }
        }
        return hasIndex;
    }
}
